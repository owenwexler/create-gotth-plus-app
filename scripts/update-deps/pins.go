// Postgres and MySQL service images stay on these major versions until someone decides to move them.
const (
	postgresImage = "postgres:18"
	mysqlImage    = "mysql:8.4"
)

var client = &http.Client{Timeout: time.Minute}

// updatePins rewrites internal/scaffold/pins.go: the latest Tailwind v4 release and its checksums,
// the latest release of each GitHub Action as a commit SHA, and the Go image for goVersion.
func updatePins(goVersion string) error {
	fmt.Println("== pins")

	tw, err := latestTag("https://github.com/tailwindlabs/tailwindcss.git", "v4")
	if err != nil {
		return err
	}
	sums, err := tailwindSums(tw)
	if err != nil {
		return err
	}

	checkout, err := pinnedAction("actions/checkout")
	if err != nil {
		return err
	}
	setupGo, err := pinnedAction("actions/setup-go")
	if err != nil {
		return err
	}

	goImage := "golang:" + goVersion + "-trixie"
	if err := imageExists("golang", goVersion+"-trixie"); err != nil {
		return err
	}

	src := fmt.Sprintf(`// Code generated by scripts/update-deps (make update-deps). DO NOT EDIT.

package scaffold

// Versions that generated Dockerfiles and CI workflows download, pinned by checksum or commit.
const (
	tailwindVersion     = %q
	tailwindSHA256X64   = %q
	tailwindSHA256Arm64 = %q

	checkoutAction = %q
	setupGoAction  = %q

	goImage       = %q
	postgresImage = %q
	mysqlImage    = %q
)
`, tw, sums["x64"], sums["arm64"], checkout, setupGo, goImage, postgresImage, mysqlImage)
	b, err := format.Source([]byte(src))
	if err != nil {
		return err
	}
	dest := filepath.Join("internal", "scaffold", "pins.go")
	if err := os.WriteFile(dest, b, 0o644); err != nil {
		return err
	}
	fmt.Printf("   tailwind %s, %s, %s, %s\n   wrote %s\n", tw, checkout, setupGo, goImage, dest)
	return nil
}

var releaseTag = regexp.MustCompile(`^v\d+\.\d+\.\d+$`)

// latestTag is the newest vX.Y.Z tag of repo, limited to major (e.g. "v4") when it is not "".
func latestTag(repo, major string) (string, error) {
	out, err := exec.Command("git", "ls-remote", "--tags", "--refs", repo).Output()
	if err != nil {
		return "", fmt.Errorf("git ls-remote %s: %w", repo, err)
	}
	best := ""
	for _, line := range strings.Split(string(out), "\n") {
		tag := strings.TrimPrefix(strings.TrimSpace(line[strings.LastIndex(line, "\t")+1:]), "refs/tags/")
		if !releaseTag.MatchString(tag) || (major != "" && semver.Major(tag) != major) {
			continue
		}
		if best == "" || semver.Compare(tag, best) > 0 {
			best = tag
		}
	}
	if best == "" {
		return "", fmt.Errorf("no release tag in %s", repo)
	}
	return best, nil
}

// pinnedAction is "owner/repo@<commit> # <tag>" for the latest release of a GitHub Action.
func pinnedAction(repo string) (string, error) {
	url := "https://github.com/" + repo + ".git"
	tag, err := latestTag(url, "")
	if err != nil {
		return "", err
	}
	// an annotated tag lists the tag object and, as ^{}, the commit it points to
	out, err := exec.Command("git", "ls-remote", url, "refs/tags/"+tag, "refs/tags/"+tag+"^{}").Output()
	if err != nil {
		return "", fmt.Errorf("git ls-remote %s: %w", repo, err)
	}
	commit := ""
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 {
			continue
		}
		if strings.HasSuffix(fields[1], "^{}") || commit == "" {
			commit = fields[0]
		}
	}
	if len(commit) != 40 {
		return "", fmt.Errorf("no commit for %s %s", repo, tag)
	}
	return repo + "@" + commit + " # " + tag, nil
}

// tailwindSums reads the release's sha256sums.txt for the two Linux builds the Dockerfile uses.
func tailwindSums(tag string) (map[string]string, error) {
	url := "https://github.com/tailwindlabs/tailwindcss/releases/download/" + tag + "/sha256sums.txt"
	body, err := get(url)
	if err != nil {
		return nil, err
	}
	sums := map[string]string{}
	sc := bufio.NewScanner(strings.NewReader(body))
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) != 2 {
			continue
		}
		for _, arch := range []string{"x64", "arm64"} {
			if strings.TrimPrefix(fields[1], "./") == "tailwindcss-linux-"+arch {
				sums[arch] = fields[0]
			}
		}
	}
	if len(sums["x64"]) != 64 || len(sums["arm64"]) != 64 {
		return nil, fmt.Errorf("%s has no checksums for the Linux builds", url)
	}
	return sums, nil
}

func imageExists(repo, tag string) error {
	if _, err := get("https://hub.docker.com/v2/repositories/library/" + repo + "/tags/" + tag); err != nil {
		return fmt.Errorf("image %s:%s: %w", repo, tag, err)
	}
	return nil
}

func get(url string) (string, error) {
	resp, err := client.Get(url)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	return string(b), err
}
